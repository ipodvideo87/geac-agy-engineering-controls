$ErrorActionPreference = 'Stop'

$null = [Console]::In.ReadToEnd()

$messageLines = @(
    'GEAC REQUIRED-GATE INTERCEPT'
    ''
    'Skills whose names begin with "required-gate-" are semantic control gates.'
    ''
    'APPLICABILITY:'
    'The prefix does NOT make every required-gate skill applicable to every task.'
    'Applicability is determined by that skill''s documented description and trigger conditions.'
    ''
    'MANDATORY ACTIVATION:'
    'When the current reasoning, evidence interpretation, proposed action, engineering status, or material output claim enters a domain covered by an available required-gate skill, that applicable gate is mandatory rather than optional.'
    ''
    'Before relying on, acting on, or emitting a material proposition in a covered domain:'
    '1. Identify the applicable required-gate skill or skills from the available skill metadata.'
    '2. Read each applicable SKILL.md if it has not already been loaded for the current work.'
    '3. Apply the loaded gate''s semantic constraints before continuing.'
    '4. Re-evaluate the proposed claim or action after the gate is applied.'
    ''
    'If applicability is materially uncertain, prefer loading the potentially applicable required-gate skill rather than silently bypassing it.'
    ''
    'A candidate claim, explanation, inference, action, recommendation, or operation generated by ordinary reasoning does not satisfy the gate by itself and does not establish, authorize, require, verify, or validate that candidate.'
    ''
    'Required-gate applicability makes activation mandatory; it does not itself establish the proposition being evaluated.'
)

$message = $messageLines -join [Environment]::NewLine

$result = [ordered]@{
    injectSteps = @(
        [ordered]@{
            ephemeralMessage = $message
        }
    )
}

$json = $result | ConvertTo-Json -Depth 8 -Compress

$utf8 = New-Object System.Text.UTF8Encoding($false)
[Console]::OutputEncoding = $utf8
[Console]::Out.WriteLine($json)